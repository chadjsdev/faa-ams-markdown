#!/usr/bin/env python3
"""Build a checklist of internal FAA links found in saved pages and PDFs.

Scans HTML and PDF files in inbox/ and archive/ (or the paths you pass), unwraps FAST's
"_leaving.cfm?uri=..." redirects, and writes curated/internal_links.md grouped
by site. Also lists public fast.faa.gov documents not yet in
curated/fast_downloads.md. Nothing is fetched; it only reads local files.
"""
from __future__ import annotations

import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path
from urllib.parse import parse_qs, unquote, urldefrag, urljoin, urlparse

from bs4 import BeautifulSoup

ROOT = Path(__file__).parent
CHECKLIST = ROOT / "curated" / "fast_downloads.md"
PUBLIC_HOSTS = {"faa.gov", "www.faa.gov", "fast.faa.gov"}
DOC_EXTS = (".pdf", ".doc", ".docx", ".ppt", ".pptx", ".xls", ".xlsx")
SKIP_PATHS = ("/resources/mail.cfm",)


def unwrap(url: str) -> str:
    """FAST wraps outbound links as /Resources/_leaving.cfm?uri=<real url>."""
    p = urlparse(url)
    if p.path.lower().endswith("_leaving.cfm"):
        uri = parse_qs(p.query).get("uri")
        if uri:
            return unquote(uri[0])
    return url


def is_internal(host: str) -> bool:
    host = host.lower()
    return (host.endswith(".faa.gov") and host not in PUBLIC_HOSTS) or host.endswith(".sharepoint.com")


def links_from_html(path: Path) -> list[tuple[str, str]]:
    soup = BeautifulSoup(path.read_text(errors="replace"), "html.parser")
    # Saved FAST pages have relative links; resolve them against the site.
    base = "https://fast.faa.gov/" if "fast" in (soup.title.get_text() if soup.title else "").lower() else "https://www.faa.gov/"
    return [(urljoin(base, a["href"]), a.get_text(" ", strip=True)) for a in soup.find_all("a", href=True)]


def links_from_pdf(path: Path) -> list[tuple[str, str]]:
    import pymupdf
    out = []
    with pymupdf.open(path) as doc:
        for page in doc:
            out += [(l["uri"], "") for l in page.get_links() if l.get("uri")]
            # Bare URLs typed into the text, not hyperlinked.
            out += [(u.rstrip(".,;)"), "") for u in re.findall(r"https?://[^\s<>\"]+", page.get_text())]
    return out


def checklist_urls() -> set[str]:
    return {u.lower() for u in re.findall(r"\((https?://[^)\s]+)\)", CHECKLIST.read_text())}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("paths", nargs="*", type=Path, default=[ROOT / "inbox", ROOT / "archive"])
    ap.add_argument("--out", type=Path, default=ROOT / "curated" / "internal_links.md")
    args = ap.parse_args()

    files = [f for p in args.paths for f in (sorted(p.rglob("*")) if p.is_dir() else [p])
             if f.suffix.lower() in (".html", ".htm", ".pdf")]
    if not files:
        print("No .html or .pdf files found.", file=sys.stderr)
        return 1

    internal: dict[str, dict[str, dict]] = defaultdict(dict)  # host -> url -> {text, found_in}
    public_new: dict[str, dict] = {}
    known = checklist_urls()

    for f in files:
        try:
            links = links_from_html(f) if f.suffix.lower() != ".pdf" else links_from_pdf(f)
        except Exception as e:
            print(f"FAIL  {f.name}: {e}", file=sys.stderr)
            continue
        for raw, text in links:
            url = urldefrag(unwrap(raw))[0].strip()
            p = urlparse(url)
            if p.scheme not in ("http", "https") or p.path.lower().startswith(SKIP_PATHS):
                continue
            if is_internal(p.netloc):
                bucket = internal[p.netloc.lower()]
            elif p.netloc.lower() == "fast.faa.gov" and p.path.lower().endswith(DOC_EXTS) and url.lower() not in known:
                bucket = public_new
            else:
                continue
            entry = bucket.setdefault(url, {"text": "", "found_in": set()})
            entry["text"] = entry["text"] or text
            entry["found_in"].add(f.name)
        print(f"read  {f.name}")

    def fmt(url: str, e: dict) -> str:
        label = e["text"] or Path(unquote(urlparse(url).path)).name or url
        return f"- [ ] [{label}]({url.replace(' ', '%20')}) — found in: {', '.join(sorted(e['found_in']))}"

    lines = [
        "# Internal FAA links checklist",
        "",
        "Generated by `extract_links.py` from saved pages/PDFs. These sites need FAA",
        "network access. Confirm you're authorized to take a document off-network",
        "before downloading it into `inbox/`.",
        "",
    ]
    for host in sorted(internal):
        lines += [f"## {host}", ""] + [fmt(u, e) for u, e in sorted(internal[host].items())] + [""]
    change_requests = {u: e for u, e in public_new.items() if "/changerequest/" in u.lower()}
    other_public = {u: e for u, e in public_new.items() if u not in change_requests}
    if other_public:
        lines += ["## Public fast.faa.gov documents not in fast_downloads.md", ""]
        lines += [fmt(u, e) for u, e in sorted(other_public.items())] + [""]
    if change_requests:
        lines += ["## AMS change requests and update summaries (public)", ""]
        lines += [fmt(u, e) for u, e in sorted(change_requests.items())] + [""]

    args.out.write_text("\n".join(lines))
    n = sum(len(v) for v in internal.values())
    print(f"\n{n} internal links across {len(internal)} sites, {len(public_new)} new public FAST docs -> {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
